def parse_price(s):
    s = s.strip()
    # Extract first number (comma as decimal separator)
    m = re.match(r'(\d+),(\d+)', s)
    if m:
        return float(f"{m.group(1)}.{m.group(2)}")
    return None

regions = []
prices = []
for line in raw.strip().split("\n"):
    if "|" in line:
        parts = line.split("|")
        name = parts[0].strip()
        price_str = parts[1].strip()
        p = parse_price(price_str)
        if p:
            regions.append(name)
            prices.append(p)

print(f"Parsed {len(regions)} regions")
print(f"Min: {min(prices):.2f}, Max: {max(prices):.2f}, Avg: {np.mean(prices):.2f}")

# Sort by price
sorted_data = sorted(zip(regions, prices), key=lambda x: x[1])

# --- Build heatmap image ---
# Grid layout: ~13 cols x 7 rows = ~91 cells, we have 87 regions
