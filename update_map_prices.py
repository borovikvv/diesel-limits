# Find the base dict and replace values
def replace_base_dict(text, new_prices):
    # Find the base = { ... } block
    start = text.find("base = {")
    if start < 0:
        print("ERROR: base = { not found")
        return text
    
    # Find the matching closing brace
    depth = 0
    brace_start = text.index("{", start)
    for i in range(brace_start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    
    # Build new base dict string
    lines = ['base = {']
    for name in sorted(new_prices.keys()):
        lines.append(f'    "{name}":{new_prices[name]},')
    lines.append('}')
    
    new_text = text[:start] + '\n'.join(lines) + text[end:]
    return new_text

