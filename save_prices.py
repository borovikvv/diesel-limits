# Сохраняем в prices
db = sqlite3.connect('/root/diesel_limits/restrictions.db')
source_url = 'https://www.petrolplus.ru/fuelindex/'
source_date = '2026-08-11'
today = datetime.now().strftime('%Y-%m-%d')

count = 0
for region, price in prices_data:
    if price > 0:  # пропускаем нулевые значения
        db.execute(
            'INSERT OR REPLACE INTO prices(region,price,source_url,source_date,updated_at) VALUES(?,?,?,?,datetime("now"))',
            (region, price, source_url, source_date)
        )
        count += 1

db.commit()
print(f"Сохранено цен в prices: {count}")

# Сохраняем в prices_history
history_count = 0
for r in db.execute('SELECT region, price FROM prices WHERE price IS NOT NULL AND price > 0'):
    db.execute(
        'INSERT OR IGNORE INTO prices_history(region,date,price) VALUES(?,?,?)',
        (r[0], today, float(r[1]))
    )
    history_count += 1

db.commit()
print(f"Сохранено записей в prices_history: {history_count}")
db.close()
