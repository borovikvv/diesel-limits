def update_prices(db):
    cur = db.cursor()
    count = 0
    for region, price in NEW_PRICES.items():
        # Try exact match, then aliases
        match = None
        for db_region in [region] + [k for k, v in REGION_ALIAS.items() if v == region]:
            cur.execute("SELECT region FROM prices WHERE region = ?", (db_region,))
            r = cur.fetchone()
            if r:
                match = db_region
                break
        if match:
            cur.execute(
                "UPDATE prices SET price=?, source_url=?, source_date=?, updated_at=datetime('now') WHERE region=?",
                (price, SOURCE_URL, TODAY, match)
            )
            count += 1
        else:
            cur.execute(
                "INSERT OR REPLACE INTO prices(region, price, source_url, source_date, updated_at) VALUES (?,?,?,?,datetime('now'))",
                (region, price, SOURCE_URL, TODAY)
            )
            count += 1
    db.commit()
    print(f"Prices updated: {count}")


def add_prices_history(db):
    cur = db.cursor()
    count = 0
    for region, price in NEW_PRICES.items():
        match = None
        for db_region in [region] + [k for k, v in REGION_ALIAS.items() if v == region]:
            cur.execute("SELECT region FROM prices WHERE region = ?", (db_region,))
            r = cur.fetchone()
            if r:
                match = db_region
                break
        if match:
            try:
                cur.execute(
                    "INSERT OR IGNORE INTO prices_history(region, date, price) VALUES (?, ?, ?)",
                    (match, TODAY, price)
                )
                count += 1
            except Exception as e:
                print(f"  history error {match}: {e}")
    db.commit()
    print(f"Prices history entries added: {count}")


def insert_restrictions(db):
    cur = db.cursor()
    source_url = "https://www.sravni.ru/novost/2026/7/13/gde-vveli-ogranicheniya-na-benzin-v-iyune-2026-goda-regiony-i-limity/"
    count = 0

    for (region, city, network, client_type, limit_type, limit_value) in NEW_RESTRICTIONS:
        # Use INSERT OR IGNORE — unique constraint covers (region, network, client_type, limit_type)
        try:
            cur.execute("""
                INSERT OR IGNORE INTO restrictions
                (region, city, network, client_type, limit_type, limit_value,
                 source_url, source_date, is_current, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, datetime('now'))
            """, (region, city or "", network or "", client_type, limit_type, limit_value,
                  source_url, "16.07.2026"))
            if cur.rowcount > 0:
                count += 1
        except Exception as e:
            print(f"  insert error: {e}")

    db.commit()
    print(f"New restrictions inserted: {count}")


