def main():
    db = sqlite3.connect(DB)
    c = db.cursor()
    
    # ── 1. Update prices ──
    price_count = 0
    for region_rosstat, price in prices.items():
        # Try direct insert
        try:
            c.execute("""
                INSERT OR REPLACE INTO prices (region, price, source_url, source_date, updated_at)
                VALUES (?, ?, ?, ?, datetime('now'))
            """, (region_rosstat, price, ROSSTAT_URL, '2026-07-13'))
            price_count += 1
        except Exception as e:
            print(f"  Price insert error for {region_rosstat}: {e}")
    
    # Also insert mapped names (for DB regions that use different naming)
    for db_region, rosstat_region in region_map.items():
        if rosstat_region in prices:
            p = prices[rosstat_region]
            try:
                c.execute("""
                    INSERT OR REPLACE INTO prices (region, price, source_url, source_date, updated_at)
                    VALUES (?, ?, ?, ?, datetime('now'))
                """, (db_region, p, ROSSTAT_URL, '2026-07-13'))
                price_count += 1
            except Exception as e:
                print(f"  Map insert error for {db_region}: {e}")
    
    print(f"Prices: {price_count} records upserted")
    
    # ── 2. Insert price history ──
    hist_count = 0
    for region_rosstat, price in prices.items():
        try:
            c.execute("""
                INSERT OR IGNORE INTO prices_history (region, date, price)
                VALUES (?, ?, ?)
            """, (region_rosstat, '2026-07-13', price))
            if c.rowcount: hist_count += 1
        except Exception as e:
            print(f"  History insert error for {region_rosstat}: {e}")
    # Also for mapped
    for db_region, rosstat_region in region_map.items():
        if rosstat_region in prices:
            p = prices[rosstat_region]
            try:
                c.execute("""
                    INSERT OR IGNORE INTO prices_history (region, date, price)
                    VALUES (?, ?, ?)
                """, (db_region, '2026-07-13', p))
                if c.rowcount: hist_count += 1
            except:
                pass
    
    print(f"Price history: {hist_count} new records")
    
    # ── 3. Insert restrictions ──
    # Mark all existing as not current
    c.execute("UPDATE restrictions SET is_current = 0")
    
    rest_count = 0
    for r in restrictions:
        region, city, network, client_type, limit_type, limit_value, prev, url, date = r
        try:
            c.execute("""
                INSERT INTO restrictions (region, city, network, client_type, limit_type, limit_value, previous_value, source_url, source_date, is_current, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1, datetime('now'), datetime('now'))
            """, (region, city, network, client_type, limit_type, limit_value, prev, url, date))
            rest_count += 1
        except Exception as e:
            print(f"  Restriction insert error for {region}: {e}")
    
    print(f"Restrictions: {rest_count} new records added")
    
    db.commit()
    db.close()

if __name__ == "__main__":
    main()
