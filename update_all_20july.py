def with_db(fn):
    db = sqlite3.connect(DB)
    try:
        fn(db)
        db.commit()
    finally:
        db.close()

def update_prices(db):
    """Update prices from Rosstat (primary) + PetrolPlus (supplement)."""
    c = db.cursor()
    inserted = 0
    # First pass: Rosstat data
    for region, price in ROSSTAT_DIESEL.items():
        n = norm(region)
        c.execute(
            "INSERT OR REPLACE INTO prices(region,price,source_url,source_date,updated_at) VALUES(?,?,?,?,datetime('now'))",
            (n, price, ROSSTAT_URL, "2026-07-13")
        )
        inserted += 1
    # Second pass: PetrolPlus for any missing
    for region, price in PP_DIESEL.items():
        if price <= 0:
            continue
        n = norm(region)
        existing = c.execute("SELECT price FROM prices WHERE region=?", (n,)).fetchone()
        if not existing:
            c.execute(
                "INSERT OR REPLACE INTO prices(region,price,source_url,source_date,updated_at) VALUES(?,?,?,?,datetime('now'))",
                (n, price, PP_URL, "2026-07-19")
            )
            inserted += 1
        # Update PetrolPlus price if it's newer (but keep Rosstat as primary — Rosstat is more official)
    print(f"Prices: {inserted} total rows updated")
    
    # Save to prices_history
    today_str = TODAY
    c.execute("CREATE TABLE IF NOT EXISTS prices_history (region TEXT, date TEXT, price REAL)")
    history_count = 0
    for r in c.execute("SELECT region, price FROM prices WHERE price IS NOT NULL"):
        c.execute("INSERT OR IGNORE INTO prices_history(region,date,price) VALUES(?,?,?)",
                  (r[0], today_str, float(r[1])))
        history_count += 1
    print(f"Prices history: {history_count} daily snapshots saved")

def insert_restrictions(db):
    c = db.cursor()
    new_count = 0
    upd_count = 0
    for r in NEW_RESTRICTIONS:
        region, city, network, client_type, limit_type, limit_value, src_url, src_date = r
        # Normalize region
        region_n = norm(region)
        network_fixed = network if network else ""
        
        existing = c.execute(
            "SELECT id, limit_value, is_current FROM restrictions WHERE region=? AND network=? AND client_type=? AND limit_type=?",
            (region_n, network_fixed, client_type, limit_type)
        ).fetchone()
        
        if existing:
            eid, old_val, cur = existing
            if old_val != limit_value:
                c.execute(
                    """UPDATE restrictions SET previous_value=?, limit_value=?, source_url=?, source_date=?, 
                       is_current=1, updated_at=datetime('now') WHERE id=?""",
                    (old_val, limit_value, src_url, src_date, eid)
                )
                upd_count += 1
            else:
                c.execute(
                    "UPDATE restrictions SET is_current=1, updated_at=datetime('now') WHERE id=?",
                    (eid,)
                )
        else:
            c.execute(
                """INSERT INTO restrictions(region,city,network,client_type,limit_type,limit_value,source_url,source_date,is_current,created_at,updated_at)
                   VALUES(?,?,?,?,?,?,?,?,1,datetime('now'),datetime('now'))""",
                (region_n, city, network_fixed, client_type, limit_type, limit_value, src_url, src_date)
            )
            new_count += 1
    
    print(f"Restrictions: {new_count} new, {upd_count} updated")

